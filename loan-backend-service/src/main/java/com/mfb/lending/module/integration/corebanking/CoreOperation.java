package com.mfb.lending.module.integration.corebanking;

public enum CoreOperation {
    FIND_CUSTOMER,
    VERIFY_CUSTOMER,
    CREATE_CUSTOMER,
    LIST_ACCOUNTS,
    VALIDATE_ACCOUNT,
    ENQUIRE_BALANCE,
    ACCOUNT_STATUS,
    CREATE_LOAN_ACCOUNT,
    GET_LOAN_ACCOUNT,
    LOAN_ACCOUNT_STATUS,
    SUBMIT_DISBURSEMENT,
    DISBURSEMENT_STATUS,
    TRANSACTION_REFERENCE,
    SUBMIT_REPAYMENT,
    REPAYMENT_STATUS,
    REVERSAL,
    TRANSACTION_POSTINGS,
    GL_TRANSACTIONS;

    public boolean safeToRetry() {
        return switch (this) {
            case FIND_CUSTOMER, VERIFY_CUSTOMER, LIST_ACCOUNTS, VALIDATE_ACCOUNT, ENQUIRE_BALANCE, ACCOUNT_STATUS,
                    GET_LOAN_ACCOUNT, LOAN_ACCOUNT_STATUS, DISBURSEMENT_STATUS, TRANSACTION_REFERENCE,
                    REPAYMENT_STATUS, TRANSACTION_POSTINGS, GL_TRANSACTIONS -> true;
            case CREATE_CUSTOMER, CREATE_LOAN_ACCOUNT, SUBMIT_DISBURSEMENT, SUBMIT_REPAYMENT, REVERSAL -> false;
        };
    }
}
